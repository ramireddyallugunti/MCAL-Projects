#ifndef MCAL_GPIO_H_
#define MCAL_GPIO_H_

#include<stdint.h>
#include"registers.h"

//enum for porttype
typedef enum
{
    GPIO_PORT_00 = 0U,
    GPIO_PORT_01,
    GPIO_PORT_02,

    GPIO_PORT_10,
    GPIO_PORT_11,
    GPIO_PORT_12,
    GPIO_PORT_13,
    GPIO_PORT_14,
    GPIO_PORT_15,

    GPIO_PORT_20,
    GPIO_PORT_21,
    GPIO_PORT_22,
    GPIO_PORT_23,
    GPIO_PORT_24,
    GPIO_PORT_25,
    GPIO_PORT_26,

    GPIO_PORT_30,
    GPIO_PORT_31,
    GPIO_PORT_32,
    GPIO_PORT_33,
    GPIO_PORT_34,

    GPIO_PORT_4O,
    GPIO_PORT_41
}Gpio_PortType;

//enum for pins
typedef enum
{
    GPIO_PIN0 = 0U,
    GPIO_PIN1,
    GPIO_PIN2,
    GPIO_PIN3,
    GPIO_PIN4,
    GPIO_PIN5,
    GPIO_PIN6,
    GPIO_PIN7,
    GPIO_PIN8,
    GPIO_PIN9,
    GPIO_PIN10,
    GPIO_PIN11,
    GPIO_PIN12,
    GPIO_PIN13,
    GPIO_PIN14,
    GPIO_PIN15

}Gpio_PinType;

//enum for direction type
typedef enum
{
    GPIO_INPUT=0U,
    GPIO_OUTPUT
}Gpio_DirectionType;

//enum for input type
typedef enum
{
    GPIO_NO_CHANGE = 0U,
    GPIO_PULL_DOWN,
    GPIO_PULL_UP,
}Gpio_InputType;

//enum for output type
typedef enum
{
    GPIO_PUSH_PULL = 0U,
    GPIO_OPEN_DRAIN,
}Gpio_OutputType;

//enum for value
typedef enum
{
    GPIO_LOW = 0U,
    GPIO_HIGH,
}Gpio_Value;

//structure on Configurations
typedef struct
{
        Gpio_PortType       port;
        Gpio_PinType        pin;
        Gpio_DirectionType  direction;
        Gpio_InputType      input;
        Gpio_OutputType     output;
}Gpio_Configuration;

//function declarations
//for initializing the GPIO
void Gpio_InitPin(const Gpio_Configuration *config);

//for writing the value into the register
void Gpio_WritePin(Gpio_PortType port,Gpio_PinType pin,Gpio_Value value);

#endif /* MCAL_GPIO_H_ */
