#ifndef MCAL_REGISTERS_H_
#define MCAL_REGISTERS_H_

#include<stdint.h>

//Base for all ports
#define P00_BASE        (0xF003A000UL)
#define P01_BASE        (0xF003A100UL)
#define P02_BASE        (0xF003A200UL)

#define P10_BASE        (0xF003AA00UL)
#define P11_BASE        (0xF003AB00UL)
#define P12_BASE        (0xF003AC00UL)
#define P13_BASE        (0xF003AD00UL)
#define P14_BASE        (0xF003AE00UL)
#define P15_BASE        (0xF003AF00UL)

#define P20_BASE        (0xF003B400UL)
#define P21_BASE        (0xF003B500UL)
#define P22_BASE        (0xF003B600UL)
#define P23_BASE        (0xF003B700UL)
#define P24_BASE        (0xF003B800UL)
#define P25_BASE        (0xF003B900UL)
#define P26_BASE        (0xF003BA00UL)

#define P30_BASE        (0xF003BE00UL)
#define P31_BASE        (0xF003BF00UL)
#define P32_BASE        (0xF003B400UL)
#define P33_BASE        (0xF003C100UL)
#define P34_BASE        (0xF003C200UL)

#define P41_BASE        (0xF003C800UL)
#define P42_BASE        (0xF003C900UL)

//offsets of the GPIO Port Registers

#define PORT_OUT_OFFSET     (0x000UL)
#define PORT_OMR_OFFSET     (0x004UL)
#define PORT_IR_OFFSET      (0x008UL)
#define PORT_IOCR0_OFFSET   (0x010UL)
#define PORT_IOCR4_OFFSET   (0x014UL)
#define PORT_IOCR8_OFFSET   (0x018UL)
#define PORT_IOCR12_OFFSET  (0x01CUL)
#define PORT_IN_OFFSET      (0x024UL)
#define PORT_PDR0_OFFSET    (0x040UL)
#define PORT_PDR1_OFFSET    (0x044UL)


//macro of hardware register

#define Reg32(address)      (*(volatile uint32_t*)(address))

//PORT Registers Access

#define PORT_OUT(base)      Reg32((base)+PORT_OUT_OFFSET)
#define PORT_OMR(base)      Reg32((base)+PORT_OMR_OFFSET)
#define PORT_IR(base)       Reg32((base)+PORT_IR_OFFSET)
#define PORT_IOCR0(base)    Reg32((base)+PORT_IOCR0_OFFSET)
#define PORT_IOCR4(base)    Reg32((base)+PORT_IOCR4_OFFSET)
#define PORT_IOCR8(base)    Reg32((base)+PORT_IOCR8_OFFSET)
#define PORT_IOCR12(base)   Reg32((base)+PORT_IOCR12_OFFSET)
#define PORT_IN(base)       Reg32((base)+PORT_IN_OFFSET)
#define PORT_PDR0(base)     Reg32((base)+PORT_PDR0_OFFSET)
#define PORT_PDR1(base)     Reg32((base)+PORT_PDR1_OFFSET)


#endif /* MCAL_REGISTERS_H_ */
