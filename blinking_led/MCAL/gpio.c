#include "registers.h"
#include "gpio.h"

static uint32_t Gpio_GetPortBase(Gpio_PortType port);
static volatile uint32_t *Gpio_GetIOCR(uint32_t base,Gpio_PinType pin);

static uint32_t Gpio_GetPortBase(Gpio_PortType port)
{
    uint32_t base = 0U;

    //based on port we assign the base address of the port and return
    switch(port)
    {
        case GPIO_PORT_00:
                          base = P00_BASE;
                          break;
        case GPIO_PORT_01:
                          base = P01_BASE;
                          break;
        case GPIO_PORT_02:
                          base = P02_BASE;
                          break;
        case GPIO_PORT_10:
                          base = P10_BASE;
                          break;
        case GPIO_PORT_11:
                          base = P11_BASE;
                          break;

        default :
                base = 0U;
    }

    return base;
}

//function for finding the offsetaddress to access the iocr based on pin
static volatile uint32_t *Gpio_GetIOCR(uint32_t port,Gpio_PinType pin)
{
    //used to store the address of iocr based on pin
    volatile uint32_t *iocr = (volatile uint32_t*)0U;

    //if pin is less than 4 to contol the IOCR of the pin we use IOCR0
    if(pin < 4)
    {
        iocr=(volatile uint32_t*)(port+PORT_IOCR0_OFFSET);
    }
    else if(pin < 8)
    {
        iocr=(volatile uint32_t*)(port+PORT_IOCR4_OFFSET);
    }
    else if(pin < 12)
    {
        iocr=(volatile uint32_t*)(port+PORT_IOCR8_OFFSET);
    }
    else
    {
        iocr=(volatile uint32_t*)(port+PORT_IOCR12_OFFSET);
    }

    return iocr;
}

//function to initialize the pin
void Gpio_InitPin(const Gpio_Configuration *config)
{

    uint32_t base;
    uint32_t pin;
    uint32_t pinIndex;
    uint32_t shift;
    uint32_t mode;

    volatile uint32_t *iocr;

    //base address of the port
    base = Gpio_GetPortBase(config -> port);
    //pin
    pin = (uint32_t) config -> pin;

    //address of iocr register
    iocr = Gpio_GetIOCR(base,pin);

    //which tells what pin control we are using
    pinIndex = pin % 4U;

    //for accessing the 5 pin control bits
    shift = (pinIndex * 8U)+3U;

    //if direction is input
    if(config -> direction == GPIO_INPUT)
    {
        //and the input is gpio pull down we use 0X01U as 5 bit value
        if(config -> input == GPIO_PULL_DOWN)
        {
            mode = 0X01U;
        }
        else if(config -> input == GPIO_PULL_UP)
        {
            mode = 0x02U;
        }
        else
        {
            mode = 0x00U;
        }
    }
    else
    {
        if(config -> output == GPIO_PUSH_PULL)
        {
            mode = 0x10U;
        }
        else
        {
            mode = 0x18U;
        }
    }

    //clearing the 5 bits
    *iocr &= ~(0x1FU << shift);

    //writing the mode that we are using for the pin
    *iocr |= ((mode & 0x1F) << shift);
}


//function to write value into output register
void Gpio_WritePin(Gpio_PortType port, Gpio_PinType pin, Gpio_Value value)
{
    uint32_t base;

    //base address of port
    base = Gpio_GetPortBase(port);

    //if value is high make the pin high else clear the pin
    if(value == GPIO_HIGH)
    {
        PORT_OMR(base) = (1U << pin);
    }
    else
    {
        PORT_OMR(base) = (1U << (pin+16U));
    }
}
