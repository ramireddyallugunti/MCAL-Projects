#include "led.h"
#include "gpio.h"

//function to initialize the LED
void Led_Init()
{

    //structure variables to store the configurations of the leds
    Gpio_Configuration led_config1;
    Gpio_Configuration led_config2;
    Gpio_Configuration led_config3;

    //configurations of the LED1
    led_config1.port = GPIO_PORT_00;
    led_config1.pin  = GPIO_PIN0;
    led_config1.direction = GPIO_OUTPUT;
    led_config1.input = GPIO_NO_CHANGE;
    led_config1.output = GPIO_PUSH_PULL;

    /*calling the init pin function by passing the
    configurations structure address of led1*/
    Gpio_InitPin(&led_config1);

    //config of LED2
    led_config2.port = GPIO_PORT_00;
    led_config2.pin  = GPIO_PIN0;
    led_config2.direction = GPIO_OUTPUT;
    led_config2.input = GPIO_NO_CHANGE;
    led_config2.output = GPIO_PUSH_PULL;

    Gpio_InitPin(&led_config2);

    //config for LED3
    led_config3.port = GPIO_PORT_00;
    led_config3.pin  = GPIO_PIN0;
    led_config3.direction = GPIO_OUTPUT;
    led_config3.input = GPIO_NO_CHANGE;
    led_config3.output = GPIO_PUSH_PULL;

    Gpio_InitPin(&led_config3);
}

//function to turn on the led
void Led_On(led_type led)
{
    //based on led we send high to the GPIO pin connected for the LED
    switch(led)
    {
        case LED1:
            Gpio_WritePin(GPIO_PORT_00,GPIO_PIN0,LED_HIGH);
            break;
        case LED2:
            Gpio_WritePin(GPIO_PORT_00,GPIO_PIN1,LED_HIGH);
            break;
        case LED3:
            Gpio_WritePin(GPIO_PORT_00,GPIO_PIN2,LED_HIGH);
            break;
        default:
            break;
    }
}

//function to turn off the led
void Led_Off(led_type led)
{
    //based on the led we send low to the gpio pin connected for the led
    switch(led)
    {
        case LED1:
            Gpio_WritePin(GPIO_PORT_00,GPIO_PIN0,LED_LOW);
            break;
        case LED2:
            Gpio_WritePin(GPIO_PORT_00,GPIO_PIN1,LED_LOW);
            break;
        case LED3:
            Gpio_WritePin(GPIO_PORT_00,GPIO_PIN2,LED_LOW);
            break;
        default:
            break;
    }
}
